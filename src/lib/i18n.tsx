const DICTS: Record<Lang, Dict> = { mn: {}, ru: RU, zh: ZH, en: EN };

function readStored(): Lang | null {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === 'mn' || v === 'ru' || v === 'zh' || v === 'en' ? v : null;
  } catch {
    return null;
  }
}

/** Утасны/браузерийн хэлээр санал болгох хэл (сонголт хийгээгүй үед). */
export function guessLang(): Lang {
  const langs = (typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : []) as string[];
  for (const l of langs) {
    const c = (l || '').toLowerCase();
    if (c.startsWith('mn')) return 'mn';
    if (c.startsWith('ru')) return 'ru';
    if (c.startsWith('zh')) return 'zh';
    if (c.startsWith('en')) return 'en';
  }
  return 'mn';
}

export function translate(lang: Lang, mn: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][mn] ?? mn;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

interface I18nValue {
  lang: Lang;
  /** Хэрэглэгч хэлээ өөрөө сонгосон эсэх (сонгоогүй бол цомгийн линк дээр асууна) */
  chosen: boolean;
  setLang: (l: Lang) => void;
  t: (mn: string, vars?: Record<string, string | number>) => string;
  locale: string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const stored = readStored();
  const [lang, setLangState] = useState<Lang>(stored ?? 'mn');
  const [chosen, setChosen] = useState<boolean>(!!stored);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    setChosen(true);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* хувийн цонх гэх мэт */ }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
  }, [lang]);

  const value = useMemo<I18nValue>(() => ({
    lang, chosen, setLang,
    t: (mn, vars) => translate(lang, mn, vars),
    locale: LOCALE[lang],
  }), [lang, chosen, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    // Provider-гүй үед (тест гэх мэт) монголоор ажиллана
    return { lang: 'mn', chosen: true, setLang: () => {}, t: (mn, vars) => translate('mn', mn, vars), locale: LOCALE.mn };
  }
  return ctx;
}
